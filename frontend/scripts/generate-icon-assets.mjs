import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const mdiIcons = require('@mdi/js');
const { icons: lucideIcons } = require('lucide-react');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const publicDirectory = path.join(root, 'public', 'generated-icons');
const catalogPath = path.join(root, 'src', 'lib', 'generatedIconCatalog.ts');
const versionPath = path.join(root, 'src', 'lib', 'generatedIconAssetVersion.ts');
const bucketCount = 32;

const hashBucket = (value) => {
  let hash = 2166136261;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return (hash >>> 0) % bucketCount;
};

const toKebabCase = (value) => value
  .replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2')
  .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
  .replace(/([A-Za-z])([0-9])/g, '$1-$2')
  .replace(/[_:\s]+/g, '-')
  .replace(/^-+|-+$/g, '')
  .toLowerCase();

const mdiOptionName = (exportName) => `mdi:${exportName
  .replace(/^mdi/, '')
  .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
  .toLowerCase()}`;

const mdiBuckets = Array.from({ length: bucketCount }, () => ({}));
const mdiExportNames = Object.keys(mdiIcons)
  .filter((name) => /^mdi[A-Z]/.test(name) && typeof mdiIcons[name] === 'string')
  .sort((a, b) => a.localeCompare(b));
for (const name of mdiExportNames) mdiBuckets[hashBucket(name)][name] = mdiIcons[name];

const lucideBuckets = Array.from({ length: bucketCount }, () => ({}));
const lucideNames = Object.keys(lucideIcons).sort((a, b) => a.localeCompare(b));
for (const name of lucideNames) {
  const slug = toKebabCase(name);
  const element = lucideIcons[name]?.render?.({}, null);
  const iconNode = element?.props?.iconNode;
  if (Array.isArray(iconNode)) lucideBuckets[hashBucket(slug)][slug] = iconNode;
}

await mkdir(publicDirectory, { recursive: true });
const mdiBucketJson = mdiBuckets.map(JSON.stringify);
const lucideBucketJson = lucideBuckets.map(JSON.stringify);
const assetVersion = createHash('sha256')
  .update(mdiBucketJson.join(''))
  .update(lucideBucketJson.join(''))
  .digest('hex')
  .slice(0, 12);
await Promise.all([
  ...mdiBucketJson.map((json, index) => writeFile(path.join(publicDirectory, `mdi-${index}.json`), json)),
  ...lucideBucketJson.map((json, index) => writeFile(path.join(publicDirectory, `lucide-${index}.json`), json)),
  writeFile(versionPath, `// Generated by scripts/generate-icon-assets.mjs.\nexport const generatedIconAssetVersion = '${assetVersion}';\n`)
]);

const suggested = [
  'Award', 'BadgeCheck', 'Crown', 'Diamond', 'Flame', 'Gem', 'Heart', 'Medal', 'ShieldCheck', 'Sparkles', 'Star', 'Trophy', 'Zap',
  ...mdiExportNames.map(mdiOptionName).sort((a, b) => a.localeCompare(b))
];
const catalogSource = `// Generated by scripts/generate-icon-assets.mjs.\n` +
  `export const generatedLucideIconNames = new Set<string>(${JSON.stringify(lucideNames)});\n` +
  `export const generatedMdiExportNames = new Set<string>(${JSON.stringify(mdiExportNames)});\n` +
  `export const generatedSuggestedIconOptions = ${JSON.stringify(suggested)} as const;\n`;
await writeFile(catalogPath, catalogSource);
